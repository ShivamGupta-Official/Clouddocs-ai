"""
CloudDocs AI — Chat & RAG Schemas

Pydantic models for question-answering requests, responses, and real source citations.
"""

from pydantic import BaseModel, Field


class SourceCitation(BaseModel):
    """Represents a genuine retrieved passage attributed to an answer."""

    citation_index: int = Field(..., description="1-indexed reference number [Source N]")
    chunk_id: str = Field(..., description="Unique chunk ID in vector database")
    document_id: str = Field(..., description="ID of source document")
    filename: str = Field(..., description="Original filename")
    page_number: int = Field(..., description="Page number in original document (1-indexed)")
    chunk_index: int = Field(..., description="Index of chunk within document")
    snippet: str = Field(..., description="Verbatim text passage used as evidence")
    relevance_score: float = Field(..., description="Cosine similarity score [0.0, 1.0]")


class ChatRequest(BaseModel):
    """User query payload for document question-answering."""

    question: str = Field(
        ..., min_length=1, description="Question to answer using uploaded documents"
    )
    top_k: int | None = Field(
        default=None, ge=1, le=20, description="Max candidate chunks to retrieve"
    )
    threshold: float | None = Field(
        default=None, ge=0.0, le=1.0, description="Minimum relevance similarity threshold"
    )
    filter_doc_id: str | None = Field(
        default=None, description="Optional document ID to restrict search"
    )


class ChatResponse(BaseModel):
    """Answer response grounded in retrieved document evidence."""

    question: str = Field(..., description="The original question")
    answer: str = Field(..., description="Grounded answer generated by LLM or refusal message")
    citations: list[SourceCitation] = Field(
        default_factory=list, description="Genuine source citations supporting the answer"
    )
    has_sufficient_evidence: bool = Field(
        ..., description="True if evidence met relevance criteria, False otherwise"
    )
    llm_provider: str = Field(
        ..., description="LLM provider used (e.g. gemini, openai, ollama, none)"
    )
    llm_model: str | None = Field(default=None, description="Model identifier if LLM was used")
    latency_seconds: float = Field(..., description="Total pipeline latency in seconds")
